/**
 * Emits the opening-catalog seed migration from the price list in
 * packages/core, so the SQL and the TypeScript can never disagree.
 *
 *   node --experimental-strip-types scripts/gen-seed-sql.ts > supabase/migrations/<ts>_pos_seed_zenverse.sql
 *
 * Idempotent on the item name: re-running against a database that already has
 * the items updates their reference cost and leaves everything else alone.
 */
import { openingCosts, unitCostOf } from '../packages/core/src/seed/openingCosts.js';

declare const process: {
  stdout: { write(s: string): void };
  stderr: { write(s: string): void };
  env: Record<string, string | undefined>;
};

/** Zenverse Cafe by default; the demo company passes its own id. */
const COMPANY_ID = process.env['COMPANY_ID'] ?? '0e573ed8-ebe8-4e32-88aa-87100e838dab';
const COMPANY_LABEL = process.env['COMPANY_LABEL'] ?? 'Zenverse Cafe';
const LOCATION_NAME = 'Main Store';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

const itemRows = openingCosts.map(
  (i) =>
    `    (${q(i.name)}, ${q(i.category)}, ${q(i.baseUnit)}, ${q(i.purchaseUnit)}, ` +
    `${i.packSize}, ${unitCostOf(i).toFixed(6)})`,
);

const sql = `-- =============================================================================
-- Digita POS — opening catalog for ${COMPANY_LABEL}
--
-- GENERATED by scripts/gen-seed-sql.ts from packages/core/src/seed/openingCosts.ts.
-- Edit the TypeScript and regenerate; do not hand-edit this file.
--
-- Seeds one location and ${openingCosts.length} inventory items with their reference
-- (standard) unit cost. No stock batches are created: the shop's actual on-hand
-- quantities are not known and must not be invented. Costing falls back to
-- standard_unit_cost until real receipts exist.
-- =============================================================================

begin;

insert into public.pos_locations (company_id, name)
values (${q(COMPANY_ID)}, ${q(LOCATION_NAME)})
on conflict do nothing;

with seed (name, category, base_unit, purchase_unit, pack_size, standard_unit_cost) as (
  values
${itemRows.join(',\n')}
),
loc as (
  select id from public.pos_locations
  where company_id = ${q(COMPANY_ID)} and lower(name) = lower(${q(LOCATION_NAME)})
  limit 1
)
insert into public.pos_items
  (company_id, location_id, name, category, item_type, base_unit, purchase_unit,
   pack_size, standard_unit_cost)
select
  ${q(COMPANY_ID)},
  (select id from loc),
  s.name,
  s.category,
  'raw_material',
  s.base_unit::public.pos_base_unit,
  s.purchase_unit,
  s.pack_size,
  s.standard_unit_cost
from seed s
on conflict (company_id, lower(name))
do update set
  category           = excluded.category,
  base_unit          = excluded.base_unit,
  purchase_unit      = excluded.purchase_unit,
  pack_size          = excluded.pack_size,
  standard_unit_cost = excluded.standard_unit_cost,
  updated_at         = now();

commit;
`;

process.stdout.write(sql);
process.stderr.write(`generated ${openingCosts.length} items for ${LOCATION_NAME}\n`);
