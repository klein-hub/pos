/**
 * Emits the full-catalog seed migration from buildSeedCatalog(), so the SQL and
 * the TypeScript cannot drift.
 *
 *   ./scripts/gen-catalog.sh > supabase/migrations/<ts>_pos_seed_catalog.sql
 *
 * The seed addresses rows by NAME, never by id. Ids in the database are random
 * uuids assigned on first insert, while the catalog in TypeScript uses slugs —
 * so every insert looks its parents up by name and every conflict target is a
 * natural key. That makes the migration idempotent: re-running it updates the
 * rows that exist rather than duplicating them, and it survives ids that were
 * assigned by an earlier seed.
 */
import { buildSeedCatalog } from '../packages/core/src/seed/catalog.js';

declare const process: {
  stdout: { write(s: string): void };
  stderr: { write(s: string): void };
  env: Record<string, string | undefined>;
};

/** Zenverse Cafe by default; the demo company passes its own id. */
const COMPANY = process.env['COMPANY_ID'] ?? '0e573ed8-ebe8-4e32-88aa-87100e838dab';
const COMPANY_LABEL = process.env['COMPANY_LABEL'] ?? 'Zenverse Cafe';

const q = (s: string) => `'${String(s).replace(/'/g, "''")}'`;
const qn = (s: string | undefined | null) => (s === undefined || s === null ? 'null' : q(s));

const catalog = buildSeedCatalog();
const { items, products, variants, modifierGroups, modifiers, recipeLines } = catalog;

const itemName = new Map(items.map((i) => [i.id, i.name]));
const productName = new Map(products.map((p) => [p.id, p.name]));
const variantById = new Map(variants.map((v) => [v.id, v]));
const modifierById = new Map(modifiers.map((m) => [m.id, m]));
const groupById = new Map(modifierGroups.map((g) => [g.id, g]));

const prep = items.filter((i) => i.itemType === 'sub_assembly');

const rows = (xs: string[]) => xs.join(',\n');

// --- prep items --------------------------------------------------------------

const prepRows = prep.map(
  (i) =>
    `    (${q(i.name)}, ${q(i.category)}, ${q(i.baseUnit)}, ${q(i.purchaseUnit)}, ` +
    `${i.packSize}, ${i.prepYieldQty ?? 'null'})`,
);

// --- products and variants ---------------------------------------------------

const productRows = products.map(
  (p) => `    (${q(p.name)}, ${q(p.category)}, ${q(p.productType)})`,
);

const variantRows = variants.map(
  (v, index) =>
    `    (${q(productName.get(v.productId) ?? '')}, ${q(v.size)}, ${v.sellingPrice}, ` +
    `${v.targetMarginPct ?? 'null'}, ${index})`,
);

// --- modifiers ---------------------------------------------------------------

const groupRows = modifierGroups.map(
  (g, index) =>
    `    (${qn(g.productId ? productName.get(g.productId) : null)}, ${q(g.name)}, ` +
    `${g.minSelect}, ${g.maxSelect}, ${index})`,
);

// Group and modifier names repeat across products — every espresso drink has
// an "Add-ons" group with an "Extra shot". Addressing them by name alone makes
// each join match several rows, which collapses into "ON CONFLICT DO UPDATE
// cannot affect row a second time". The product is what disambiguates.
const modifierRows = modifiers.map((m, index) => {
  const group = groupById.get(m.groupId);
  const owner = group?.productId ? productName.get(group.productId) : null;
  return `    (${qn(owner)}, ${q(group?.name ?? '')}, ${q(m.name)}, ${m.priceDelta}, ${index})`;
});

// --- recipe lines, one block per owner kind ----------------------------------

const variantLines = recipeLines.filter((l) => l.ownerType === 'variant');
const prepLines = recipeLines.filter((l) => l.ownerType === 'prep');
const modifierLines = recipeLines.filter((l) => l.ownerType === 'modifier');

const variantLineRows = variantLines.map((l) => {
  const v = variantById.get(l.ownerId);
  return (
    `    (${q(productName.get(v?.productId ?? '') ?? '')}, ${q(v?.size ?? '')}, ` +
    `${q(itemName.get(l.itemId) ?? '')}, ${l.dose.qty})`
  );
});

const prepLineRows = prepLines.map(
  (l) => `    (${q(itemName.get(l.ownerId) ?? '')}, ${q(itemName.get(l.itemId) ?? '')}, ${l.dose.qty})`,
);

const modifierLineRows = modifierLines.map((l) => {
  const m = modifierById.get(l.ownerId);
  const group = m ? groupById.get(m.groupId) : undefined;
  const owner = group?.productId ? productName.get(group.productId) : null;
  return (
    `    (${qn(owner)}, ${q(group?.name ?? '')}, ${q(m?.name ?? '')}, ` +
    `${q(itemName.get(l.itemId) ?? '')}, ${l.dose.qty})`
  );
});

const sql = `-- =============================================================================
-- Digita POS — full catalog for ${COMPANY_LABEL}
--
-- GENERATED by scripts/gen-catalog-sql.ts from packages/core/src/seed/catalog.ts.
-- Regenerate with ./scripts/gen-catalog.sh; do not hand-edit.
--
-- Adds what 20260812093000 left out: the ${prep.length} prep items, ${products.length} products,
-- ${variants.length} variants, ${modifierGroups.length} modifier group(s), ${modifiers.length} modifier(s) and
-- ${recipeLines.length} recipe lines. Raw-material items are already seeded.
--
-- Every row is addressed by NAME and every conflict target is a natural key, so
-- this is idempotent and independent of the random uuids assigned earlier.
--
-- NOTE: ingredient costs are the shop's real price list, but the recipe
-- QUANTITIES are starter assumptions and must be confirmed against how the bar
-- actually builds each drink before any margin here is treated as fact.
-- =============================================================================

begin;

-- --- prep items (sub-assemblies) ---------------------------------------------

with seed (name, category, base_unit, purchase_unit, pack_size, prep_yield_qty) as (
  values
${rows(prepRows)}
)
insert into public.pos_items
  (company_id, location_id, name, category, item_type, base_unit, purchase_unit,
   pack_size, prep_yield_qty)
select
  ${q(COMPANY)},
  (select id from public.pos_locations where company_id = ${q(COMPANY)} order by created_at limit 1),
  s.name, s.category, 'sub_assembly', s.base_unit::public.pos_base_unit, s.purchase_unit,
  s.pack_size, s.prep_yield_qty
from seed s
on conflict (company_id, lower(name)) do update set
  category       = excluded.category,
  item_type      = excluded.item_type,
  base_unit      = excluded.base_unit,
  pack_size      = excluded.pack_size,
  prep_yield_qty = excluded.prep_yield_qty,
  updated_at     = now();

-- --- products ----------------------------------------------------------------

with seed (name, category, product_type) as (
  values
${rows(productRows)}
)
insert into public.pos_products (company_id, name, category, product_type)
select ${q(COMPANY)}, s.name, s.category, s.product_type::public.pos_product_type
from seed s
on conflict (company_id, lower(name)) do update set
  category     = excluded.category,
  product_type = excluded.product_type,
  updated_at   = now();

-- --- variants ----------------------------------------------------------------

with seed (product_name, size, selling_price, target_margin_pct, sort_order) as (
  values
${rows(variantRows)}
)
insert into public.pos_product_variants
  (company_id, product_id, size, selling_price, target_margin_pct, sort_order)
select ${q(COMPANY)}, p.id, s.size, s.selling_price, s.target_margin_pct, s.sort_order
from seed s
join public.pos_products p
  on p.company_id = ${q(COMPANY)} and lower(p.name) = lower(s.product_name)
on conflict (product_id, lower(size)) do update set
  selling_price     = excluded.selling_price,
  target_margin_pct = excluded.target_margin_pct,
  sort_order        = excluded.sort_order,
  updated_at        = now();

-- --- modifier groups and modifiers -------------------------------------------

with seed (product_name, name, min_select, max_select, sort_order) as (
  values
${rows(groupRows.length > 0 ? groupRows : ['    (null::text, null::text, null::int, null::int, null::int)'])}
),
resolved as (
  select
    (select p.id from public.pos_products p
      where p.company_id = ${q(COMPANY)} and lower(p.name) = lower(s.product_name)) as product_id,
    s.*
  from seed s
  where s.name is not null
)
insert into public.pos_modifier_groups
  (company_id, product_id, name, min_select, max_select, sort_order)
select ${q(COMPANY)}, r.product_id, r.name, r.min_select, r.max_select, r.sort_order
from resolved r
-- Identified by product plus name: several products each have an "Add-ons"
-- group, and they are not the same group.
where not exists (
  select 1 from public.pos_modifier_groups g
  where g.company_id = ${q(COMPANY)}
    and g.product_id is not distinct from r.product_id
    and lower(g.name) = lower(r.name)
);

with seed (product_name, group_name, name, price_delta, sort_order) as (
  values
${rows(modifierRows.length > 0 ? modifierRows : ['    (null::text, null::text, null::text, null::int, null::int)'])}
),
resolved as (
  select g.id as group_id, s.name, s.price_delta, s.sort_order
  from seed s
  join public.pos_modifier_groups g
    on g.company_id = ${q(COMPANY)}
   and lower(g.name) = lower(s.group_name)
   and g.product_id is not distinct from
       (select p.id from public.pos_products p
         where p.company_id = ${q(COMPANY)} and lower(p.name) = lower(s.product_name))
  where s.name is not null
)
insert into public.pos_modifiers (company_id, group_id, name, price_delta, sort_order)
select ${q(COMPANY)}, r.group_id, r.name, r.price_delta, r.sort_order
from resolved r
where not exists (
  select 1 from public.pos_modifiers m
  where m.group_id = r.group_id and lower(m.name) = lower(r.name)
);

-- --- recipe lines: prep items ------------------------------------------------
-- Prep recipes first: a drink's roll-up reads through them.

with seed (owner_name, item_name, qty) as (
  values
${rows(prepLineRows)}
)
insert into public.pos_recipe_lines (company_id, owner_id, owner_type, item_id, qty)
select ${q(COMPANY)}, owner.id, 'prep', ing.id, s.qty
from seed s
join public.pos_items owner
  on owner.company_id = ${q(COMPANY)} and lower(owner.name) = lower(s.owner_name)
join public.pos_items ing
  on ing.company_id = ${q(COMPANY)} and lower(ing.name) = lower(s.item_name)
on conflict (owner_id, item_id) do update set qty = excluded.qty, updated_at = now();

-- --- recipe lines: variants --------------------------------------------------

with seed (product_name, size, item_name, qty) as (
  values
${rows(variantLineRows)}
)
insert into public.pos_recipe_lines (company_id, owner_id, owner_type, item_id, qty)
select ${q(COMPANY)}, v.id, 'variant', ing.id, s.qty
from seed s
join public.pos_products p
  on p.company_id = ${q(COMPANY)} and lower(p.name) = lower(s.product_name)
join public.pos_product_variants v
  on v.product_id = p.id and lower(v.size) = lower(s.size)
join public.pos_items ing
  on ing.company_id = ${q(COMPANY)} and lower(ing.name) = lower(s.item_name)
on conflict (owner_id, item_id) do update set qty = excluded.qty, updated_at = now();

-- --- recipe lines: modifiers -------------------------------------------------

with seed (product_name, group_name, modifier_name, item_name, qty) as (
  values
${rows(modifierLineRows.length > 0 ? modifierLineRows : ['    (null::text, null::text, null::text, null::text, null::numeric)'])}
)
insert into public.pos_recipe_lines (company_id, owner_id, owner_type, item_id, qty)
select ${q(COMPANY)}, m.id, 'modifier', ing.id, s.qty
from seed s
join public.pos_modifier_groups g
  on g.company_id = ${q(COMPANY)}
 and lower(g.name) = lower(s.group_name)
 and g.product_id is not distinct from
     (select p.id from public.pos_products p
       where p.company_id = ${q(COMPANY)} and lower(p.name) = lower(s.product_name))
join public.pos_modifiers m
  on m.group_id = g.id and lower(m.name) = lower(s.modifier_name)
join public.pos_items ing
  on ing.company_id = ${q(COMPANY)} and lower(ing.name) = lower(s.item_name)
where s.modifier_name is not null
on conflict (owner_id, item_id) do update set qty = excluded.qty, updated_at = now();

commit;
`;

process.stdout.write(sql);
process.stderr.write(
  `generated: ${prep.length} prep items, ${products.length} products, ${variants.length} variants, ` +
    `${modifierGroups.length} groups, ${modifiers.length} modifiers, ${recipeLines.length} recipe lines\n`,
);
