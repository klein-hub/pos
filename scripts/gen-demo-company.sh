#!/usr/bin/env bash
#
# Regenerates the demo-company migration: the company row, a location, the
# price list and the full catalog, all scoped to the demo company_id.
#
#   ./scripts/gen-demo-company.sh > supabase/migrations/<timestamp>_pos_demo_company.sql
#
# Isolation is by company_id, the tenant key every query already filters by and
# RLS already enforces — not by an is_demo flag each future query would have to
# remember.
set -euo pipefail
# pipefail matters here: these generators are piped through `strip`, and
# without it a failing generator would be masked by sed's exit code.

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEMO_ID=${DEMO_COMPANY_ID:-11111111-2222-4333-8444-555555555555}
DEMO_LABEL='Zenverse Cafe (Demo)'

cat <<SQL
-- =============================================================================
-- Digita POS — demo company
--
-- GENERATED by scripts/gen-demo-company.sh; do not hand-edit.
--
-- A sandbox that behaves exactly like the real thing: same tables, same RLS,
-- real persistence — but under its own company_id, so nothing recorded here
-- can reach a live report.
--
-- NOTE: \`companies\` is shared with the payroll and attendance apps, so this
-- row shows up in their company pickers too. Hence the explicit "(Demo)" in
-- the name and the brand line — someone meeting it there should not have to
-- guess what it is.
--
-- Access is super-admin only, and enforced by the database rather than only by
-- the UI: is_company_member() is true for a super admin on any company, and no
-- profile points at this one, so an ordinary user is refused by RLS.
-- =============================================================================

begin;

insert into public.companies (id, name, brand, currency, timezone)
values ('$DEMO_ID', '$DEMO_LABEL', 'Digita POS demo — not real trading data', 'PHP', 'Asia/Manila')
on conflict (id) do update set name = excluded.name, brand = excluded.brand;
SQL

# Both generators emit a full migration; strip their transaction wrappers so
# everything lands in this one.
strip() { sed -e '1,/^begin;$/d' -e '/^commit;$/d'; }

COMPANY_ID="$DEMO_ID" COMPANY_LABEL="$DEMO_LABEL" "$ROOT/scripts/run-ts.sh" scripts/gen-seed-sql.ts | strip
COMPANY_ID="$DEMO_ID" COMPANY_LABEL="$DEMO_LABEL" "$ROOT/scripts/gen-catalog.sh" | strip

echo "commit;"
